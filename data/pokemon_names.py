def translate_name(name):
    """将中文名转换为英文名"""
    name = name.strip()
    if name in POKEMON_NAMES:
        return POKEMON_NAMES[name]
    return name.lower()

def get_type_color(type_name):
    """获取类型对应的颜色"""
    return TYPE_COLORS.get(type_name, "#999999")
